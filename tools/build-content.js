import fs from 'node:fs';
import path from 'node:path';
import { Script } from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));

const scripts = {
  'content.js': [
    'compat/selectors.js', 'context-data.js', 'settings.js',
    'ui-icons.js', 'export.js', 'chatlog.js', 'inspector.js', 'rename.js', 'content.js',
  ],
  'net-sniffer.js': ['context-data.js', 'net-sniffer.js'],
};

for (const [target, sources] of Object.entries(scripts)) {
  const parts = sources.map(source => {
    const code = fs.readFileSync(path.join(root, 'src', source), 'utf8').trimStart()
      .replace(/\r\n/g, '\n')
      .replace(/^import\s[\s\S]*?from\s+['"][^'"]+['"];[^\S\n]*\n/gm, '')
      .replace(/^export\s+(?=(?:async\s+function|function|const|let|var|class)\b)/gm, '')
      .trim();
    return `// src/${source}\n${code}`;
  });
  const bundle = `// Modus ${manifest.version} — generated by npm run build.\n(function () {\n'use strict';\n${parts.join('\n\n')}\n})();\n`;
  new Script(bundle, { filename: target });
  fs.writeFileSync(path.join(root, target), bundle);
  console.log(`Built ${target} (${Buffer.byteLength(bundle)} bytes)`);
}
